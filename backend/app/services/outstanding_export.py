WIDTHS = (8, 40, 12, 18, 14, 30, 16, 12, 12)
_BAD_SHEET_CHARS = re.compile(r"[\[\]:*?/\\]")


def outstanding_items(session: Session, project_id: int, filters: Filters | None = None, *,
                      today: date | None = None) -> list[Item]:
    f = replace(filters or Filters(), outstanding=True)
    return load_items(session, project_id, f, today=today)


def _sheet_name(name: str, used: set[str]) -> str:
    base = _BAD_SHEET_CHARS.sub("_", name).strip("'") or "_"
    candidate, n = base[:31], 2
    while candidate.casefold() in used:
        suffix = f" ({n})"
        candidate, n = base[:31 - len(suffix)] + suffix, n + 1
    used.add(candidate.casefold())
    return candidate


def export(session: Session, project_id: int, filters: Filters | None = None, *,
           lang: str = "en", today: date | None = None) -> bytes:
    today = today or date.today()
    t, labels = TEXT[lang], mx.TEXT[lang]["status"]
    project = get_project(session, project_id)
    items = outstanding_items(session, project_id, filters, today=today)
    by_vendor: dict[str, list[Item]] = defaultdict(list)
    for it in items:
        by_vendor[it.vendor or ""].append(it)
    vendors = sorted(by_vendor, key=lambda v: (v == "", v.casefold()))
    footer = t["footer"].format(p=mx.PLATFORM, code=project.code,
                                at=f"{datetime.now():%Y-%m-%d %H:%M}")

    wb = Workbook()
    ws = wb.active
    ws.title = _sheet_name(t["summary"], used := set())
    _head(ws, t, project, t["summary"], today)
    mx._header_cells(ws, 5, t["summary_cols"], (40, 14, 14))
    rows = [(v or t["none"], len(by_vendor[v]), sum(i.overdue for i in by_vendor[v])) for v in vendors]
    rows.append((t["total"], len(items), sum(i.overdue for i in items)))
    for r, values in enumerate(rows, start=6):
        for col, v in enumerate(values, start=1):
            ws.cell(r, col, v).border = mx.BOX
    for col in range(1, 4):
        ws.cell(5 + len(rows), col).font = Font(bold=True)
    _setup(ws, footer)

    for vendor in vendors:
        sheet = wb.create_sheet(_sheet_name(vendor or t["none"], used))
        _head(sheet, t, project, vendor or t["none"], today)
        mx._header_cells(sheet, 5, t["cols"], WIDTHS)
        for r, it in enumerate(by_vendor[vendor], start=6):
            key = "O" if it.overdue else mx.KEY_OF[DeliverableStatus(it.status)]
            days = (today - it.due_date).days if it.overdue else None
            values = (it.submittal_no, it.document_type_name, it.milestone_code, it.module_name,
                      it.equipment_tag, it.equipment_name, labels[key], it.due_date, days)
            for col, v in enumerate(values, start=1):
                c = sheet.cell(r, col, v)
                c.border = mx.BOX
                if isinstance(v, date):
                    c.number_format, c.alignment = "yyyy-mm-dd", Alignment(horizontal="center")
            fill, font = mx.COLORS[key]
            sc = sheet.cell(r, 7)
            sc.fill, sc.font = PatternFill("solid", fgColor=fill), Font(bold=True, color=font)
        sheet.auto_filter.ref = f"A5:I{5 + len(by_vendor[vendor])}"
        sheet.freeze_panes = "A6"
        _setup(sheet, footer)
    if not items:
        ws.cell(6, 1, t["no_items"])

    wb.properties.creator = f"{mx.PLATFORM} (system generated)"
    wb.properties.title = f"{project.code} {t['title']}"
    buffer = io.BytesIO()
    wb.save(buffer)
    return buffer.getvalue()


def _head(ws, t: dict, project, vendor: str, today: date) -> None:
    ws["A1"] = t["title"]
    ws["A1"].font = Font(size=16, bold=True, color=mx.NAVY)
    for r, (k, v) in enumerate(((t["project"], f"{project.name} ({project.code})"),
                                (t["vendor"], vendor)), start=2):
        ws.cell(r, 1, k).font = Font(bold=True, color="595959")
        ws.cell(r, 2, v)
    ws.cell(2, 5, t["as_of"]).font = Font(bold=True, color="595959")
    c = ws.cell(2, 6, today)
    c.number_format, c.alignment = "yyyy-mm-dd", Alignment(horizontal="left")


def _setup(ws, footer: str) -> None:
    ws.page_setup.orientation, ws.page_setup.paperSize = "landscape", ws.PAPERSIZE_A4
    ws.page_setup.fitToWidth, ws.page_setup.fitToHeight = 1, 0
    ws.sheet_properties.pageSetUpPr.fitToPage = True
    ws.print_title_rows = "5:5"
    ws.oddFooter.left.text, ws.oddFooter.left.size = footer, 7
