"""缺件清单导出 Excel（PRD F7.5 最后一句；可按供应商发出）。

缺件 = 还没收到文件的（不含已批准）+ 需修改重交的（见 deliverables.is_outstanding）。第一张是汇总表，之后每个供应商一张；
没有对应设备的应交项（整个种类、按模块）和没填供应商的设备放"未指定供应商"表。
只放给供应商看也没问题的信息：不导出内部备注、状态依据。
"""

