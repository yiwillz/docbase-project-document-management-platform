def parse_return(session: Session, project_id: int, data: bytes, *, filename: str | None = None
                 ) -> dict[str, Any]:
    """解析客户填好退回的传送单：比对每行的审核代码、回复日期、意见。"""
    def fail(code: str, message: str) -> dict[str, Any]:
        return {"ok": False, "changes": [], "warnings": [], "errors": [
            {"code": code, "message": message, "row": None}], "transmittal_id": None}

    try:
        wb = load_workbook(io.BytesIO(data), data_only=True)
    except Exception:  # noqa: BLE001  不是 Excel 文件
        return fail("transmittal_import.not_excel", "不是 Excel 文件")
    if "_meta" not in wb.sheetnames:
        return fail("transmittal_import.not_platform_file", "不是平台导出的传送单")
    meta = {r[0].value: r[1].value for r in wb["_meta"].iter_rows(max_col=2)}
    if meta.get("format") != FORMAT or meta.get("version") != FORMAT_VERSION:
        return fail("transmittal_import.not_platform_file", "不是平台导出的传送单")
    if meta.get("project_id") != project_id:
        return fail("transmittal_import.other_project", f"这是项目 {meta.get('project_code')} 的传送单")
    t = session.get(Transmittal, meta.get("transmittal_id"))
    if t is None or t.project_id != project_id:
        return fail("transmittal_import.not_found", f"找不到传送单 {meta.get('number')}")
    if t.void:
        return fail("transmittal_import.void", f"传送单 {t.number} 已作废")

    ws = wb.worksheets[0]
    codes = codes_svc.list_codes(session, project_id)
    items = {i.id: i for i in svc.items_of(session, t.id)}
    ref = mx._cell_text(ws[meta["ref_cell"]].value) or (
        f"传送单导回（{filename}）" if filename else "传送单导回")
    changes, warnings, errors = [], [], []
    for r in range(int(meta["header_row"]) + 1, int(meta["last_row"]) + 1):
        item = items.get(ws.cell(r, C_ITEM).value)
        label = mx._cell_text(ws.cell(r, C_DOC_NO).value)
        if item is None:
            errors.append({"code": "transmittal_import.unknown_row", "row": r,
                           "message": f"第 {r} 行（{label}）不在这张传送单上"})
            continue
        code_text = mx._cell_text(ws.cell(r, C_CODE).value)
        if code_text is None:
            continue  # 没填的不动
        code = codes_svc.find_code(codes, code_text)
        if code is None:
            errors.append({"code": "transmittal_import.bad_code", "row": r,
                           "message": f"第 {r} 行（{label}）：审核代码 {code_text} 不认识"})
            continue
        try:
            reply_date = mx._cell_date(ws.cell(r, C_DATE).value)
        except ValueError as exc:
            errors.append({"code": "transmittal_import.bad_date", "row": r,
                           "message": f"第 {r} 行（{label}）：{exc}"})
            continue
        if reply_date is None:
            warnings.append({"code": "transmittal_import.no_reply_date", "row": r,
                             "message": f"第 {r} 行（{label}）没填回复日期"})
        comments = mx._cell_text(ws.cell(r, C_COMMENTS).value)
        new = {"review_code": code.code, "reply_date": mx._iso(reply_date),
               "reply_comments": comments}
        old = {"review_code": item.review_code, "reply_date": mx._iso(item.reply_date),
               "reply_comments": item.reply_comments}
        diff = {k: [old[k], v] for k, v in new.items() if old[k] != v}
        if diff:
            changes.append({"item_id": item.id, "row": r, "label": label, "changes": diff})
    return {"ok": not errors, "transmittal_id": t.id, "number": t.number, "reply_ref": ref,
            "changes": changes, "warnings": warnings, "errors": errors}


def apply_return(session: Session, project_id: int, transmittal_id: int, changes: list[dict[str, Any]],
                 reply_ref: str, actor: Actor) -> dict[str, int]:
    if not changes:
        return {"updated": 0, "unchanged": 0}
    items, existing = [], {i.id: i for i in svc.items_of(session, transmittal_id)}
    for change in changes:
        values = {k: v[1] for k, v in change["changes"].items()}
        current = existing[change["item_id"]]
        reply_date = values.get("reply_date", mx._iso(current.reply_date))
        items.append({
            "item_id": change["item_id"], "code": values.get("review_code", current.review_code),
            "reply_date": date.fromisoformat(reply_date) if reply_date else None,
            "reply_comments": values.get("reply_comments", current.reply_comments)})
    return svc.set_reply(session, project_id, transmittal_id, {"reply_ref": reply_ref}, actor,
                         items=items, source=ReplySource.TRANSMITTAL_RETURN,
                         reason=f"客户回复：{reply_ref}")
