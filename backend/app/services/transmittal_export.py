@dataclass
class Line:
    item_id: int
    doc_no: str
    title: str
    where: str | None
    revision: str | None
    code: str | None
    reply_date: date | None
    comments: str | None


def _lines(session: Session, t: Transmittal) -> list[Line]:
    items = svc.items_of(session, t.id)
    deliverables = {d.id: d for d in session.scalars(
        select(Deliverable).where(Deliverable.id.in_([i.deliverable_id for i in items])))} if items else {}
    docs = {d.id: d for d in session.scalars(select(DocumentType).where(
        DocumentType.id.in_({d.document_type_id for d in deliverables.values()})))} if items else {}
    equipment = {e.id: e for e in session.scalars(select(Equipment).where(
        Equipment.project_id == t.project_id))}
    modules = {m.id: m for m in session.scalars(select(Module).where(Module.project_id == t.project_id))}
    lines, keys = [], {}
    for item in items:
        d = deliverables[item.deliverable_id]
        doc = docs[d.document_type_id]
        e = equipment.get(d.equipment_id) if d.equipment_id else None
        module = modules.get(d.module_id) if d.module_id else None
        if e is not None:
            # 没编号的设备：文件编号不带设备编号，用名称区分
            doc_no = f"{doc.submittal_no}.{e.tag}" if e.tag else doc.submittal_no
            where = f"{e.tag} {e.name}" if e.tag else e.name
        else:
            doc_no, where = doc.submittal_no, module.name if module else None
        keys[item.id] = (_number(doc.submittal_no), module.sort_order if module else 0,
                         e.sort_order if e else 0, item.id)
        lines.append(Line(item.id, doc_no, doc.name, where, item.revision, item.review_code,
                          item.reply_date, item.reply_comments))
    lines.sort(key=lambda ln: keys[ln.item_id])
    return lines


def export(session: Session, project_id: int, transmittal_id: int, *, lang: str = "en",
           fmt: str = "xlsx") -> bytes:
    t = svc.get_transmittal(session, project_id, transmittal_id)
    project = get_project(session, project_id)
    codes = codes_svc.list_codes(session, project_id)
    lines = _lines(session, t)
    ctx = {"t": TEXT[lang], "lang": lang, "project": project, "tr": t, "lines": lines,
           "codes": codes,
           "footer": TEXT[lang]["footer"].format(p=mx.PLATFORM, no=t.number,
                                                 at=f"{datetime.now():%Y-%m-%d %H:%M}")}
    return _excel(ctx) if fmt == "xlsx" else _pdf(ctx)


def _code_labels(codes, lang: str) -> list[str]:
    return [f"{c.code} = {c.label_zh if lang == 'zh' and c.label_zh else c.label_en}" for c in codes]


def _excel(ctx: dict[str, Any]) -> bytes:
    t, p, tr, lines = ctx["t"], ctx["project"], ctx["tr"], ctx["lines"]
    wb = Workbook()
    ws = wb.active
    ws.title = t["sheet"]
    ws.merge_cells("A1:E1")
    ws["A1"] = t["title"]
    ws["A1"].font = Font(size=16, bold=True, color=mx.NAVY)
    info = (f"{p.name} ({p.code})", p.client_name or "", p.contractor_name or "")
    meta = (tr.number, tr.submitted_date, t["void"] if tr.void else t["issued"])
    for r, (k1, v1, k2, v2) in enumerate(zip(t["info"], info, t["meta"], meta, strict=True), start=2):
        ws.cell(r, 1, k1).font = Font(bold=True, color="595959")
        ws.merge_cells(start_row=r, start_column=2, end_row=r, end_column=4)
        ws.cell(r, 2, v1)
        ws.cell(r, 6, k2).font = Font(bold=True, color="595959")
        ws.merge_cells(start_row=r, start_column=7, end_row=r, end_column=8)
        c = ws.cell(r, 7, v2)
        c.alignment = Alignment(horizontal="left")
        if isinstance(v2, date):
            c.number_format = "yyyy-mm-dd"
    ws.cell(5, 1, t["subject"]).font = Font(bold=True, color="595959")
    ws.merge_cells("B5:H5")
    ws["B5"] = tr.subject
    header = 7
    mx._header_cells(ws, header, t["columns"], (6, 16, 40, 26, 8, 12, 13, 40))
    dv = DataValidation(type="list", allow_blank=True,
                        formula1='"' + ",".join(c.code for c in ctx["codes"]) + '"')
    ws.add_data_validation(dv)
    fill = PatternFill("solid", fgColor=FILL_IN)
    r = header
    for i, ln in enumerate(lines, start=1):
        r += 1
        values = (i, ln.doc_no, ln.title, ln.where, ln.revision, ln.code, ln.reply_date, ln.comments)
        for col, v in enumerate(values, start=1):
            c = ws.cell(r, col, v)
            c.border = mx.BOX
            c.alignment = Alignment(vertical="center", wrap_text=col in (C_TITLE, C_COMMENTS))
            if col >= C_CODE:
                c.fill = fill
        ws.cell(r, C_DATE).number_format = "yyyy-mm-dd"
        ws.cell(r, C_CODE).alignment = Alignment(horizontal="center")
        dv.add(ws.cell(r, C_CODE))
        ws.cell(r, C_ITEM, ln.item_id)
    last = r
    ws.column_dimensions["K"].hidden = True
    ws.freeze_panes = ws.cell(header + 1, 1)

    r = last + 2
    ws.cell(r, 1, t["instruction"]).font = Font(italic=True, color="595959")
    r += 1
    ws.cell(r, 1, t["reply_ref"]).font = Font(bold=True)
    ws.merge_cells(start_row=r, start_column=1, end_row=r, end_column=2)
    ref_cell = ws.cell(r, 3)
    ref_cell.fill, ref_cell.border = fill, mx.BOX
    r += 2
    ws.cell(r, 1, t["codes"]).font = Font(bold=True)
    for j, label in enumerate(_code_labels(ctx["codes"], ctx["lang"])):
        ws.cell(r + 1 + j // 3, 2 + (j % 3) * 2, label)
    r += 3 + (len(ctx["codes"]) - 1) // 3
    for col, role in ((2, t["sign"][0]), (6, t["sign"][1])):
        ws.cell(r, col, role).font = Font(bold=True, color=mx.NAVY)
        for j, label in enumerate(t["sign_fields"], start=1):
            ws.cell(r + j, col, f"{label}:").font = Font(color="595959")
    ws.cell(r + 1, 3, p.mdl_prepared_by or tr.created_by_name)

    ws.page_setup.orientation, ws.page_setup.paperSize = "landscape", ws.PAPERSIZE_A4
    ws.page_setup.fitToWidth, ws.page_setup.fitToHeight = 1, 0
    ws.sheet_properties.pageSetUpPr.fitToPage = True
    ws.print_title_rows = f"{header}:{header}"
    ws.oddFooter.left.text, ws.oddFooter.left.size = ctx["footer"], 7

    meta_ws = wb.create_sheet("_meta")
    for row in (("format", FORMAT), ("version", FORMAT_VERSION), ("project_id", p.id),
                ("project_code", p.code), ("transmittal_id", tr.id), ("number", tr.number),
                ("header_row", header), ("last_row", last), ("ref_cell", ref_cell.coordinate)):
        meta_ws.append(row)
    meta_ws.sheet_state = "hidden"
    wb.properties.creator = f"{mx.PLATFORM} (system generated)"
    wb.properties.title = f"{tr.number} {t['title']}"
    buffer = io.BytesIO()
    wb.save(buffer)
    return buffer.getvalue()


def _pdf(ctx: dict[str, Any]) -> bytes:
    t, p, tr = ctx["t"], ctx["project"], ctx["tr"]
    regular, bold = mx._fonts(ctx["lang"])
    navy, grid = colors.HexColor("#" + mx.NAVY), colors.HexColor("#" + mx.GRID)
    small = ParagraphStyle("s", fontName=regular, fontSize=8, leading=10)
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=landscape(A4), leftMargin=12 * mm, rightMargin=12 * mm,
                            topMargin=12 * mm, bottomMargin=14 * mm,
                            title=f"{tr.number} {t['title']}", author=f"{mx.PLATFORM} (system generated)")
    story: list[Any] = [Paragraph(f"<font size=16 color='#{mx.NAVY}'><b>{escape(t['title'])}</b></font>",
                                  ParagraphStyle("t", parent=small, fontName=bold, leading=20,
                                                 spaceAfter=3 * mm))]
    info = (f"{p.name} ({p.code})", p.client_name or "", p.contractor_name or "")
    meta = (tr.number, f"{tr.submitted_date:%Y-%m-%d}" if tr.submitted_date else "",
            t["void"] if tr.void else t["issued"])
    rows = [[k1, v1, k2, v2] for k1, v1, k2, v2 in zip(t["info"], info, t["meta"], meta, strict=True)]
    rows.append([t["subject"], Paragraph(escape(tr.subject or ""), small), "", ""])
    head = Table(rows, colWidths=[25 * mm, 130 * mm, 30 * mm, 88 * mm])
    head.setStyle(TableStyle([
        ("FONT", (0, 0), (-1, -1), regular, 8.5), ("FONT", (0, 0), (0, -1), bold, 8.5),
        ("FONT", (2, 0), (2, -1), bold, 8.5), ("SPAN", (1, -1), (-1, -1)),
        ("TEXTCOLOR", (0, 0), (0, -1), colors.HexColor("#595959")),
        ("TEXTCOLOR", (2, 0), (2, -1), colors.HexColor("#595959")),
        ("LINEBELOW", (0, -1), (-1, -1), 1.2, navy)]))
    story += [head, Spacer(1, 5 * mm)]
    data: list[list[Any]] = [list(t["columns"])]
    for i, ln in enumerate(ctx["lines"], start=1):
        data.append([i, ln.doc_no, Paragraph(escape(ln.title), small), Paragraph(escape(ln.where or ""), small),
                     ln.revision or "", ln.code or "", f"{ln.reply_date:%Y-%m-%d}" if ln.reply_date else "",
                     Paragraph(escape(ln.comments or ""), small)])
    table = Table(data, colWidths=[w * mm for w in (9, 26, 70, 45, 13, 19, 20, 71)], repeatRows=1)
    table.setStyle(TableStyle([
        ("FONT", (0, 0), (-1, 0), bold, 8), ("BACKGROUND", (0, 0), (-1, 0), navy),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white), ("ALIGN", (0, 0), (-1, 0), "CENTER"),
        ("FONT", (0, 1), (-1, -1), regular, 8), ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("GRID", (0, 0), (-1, -1), 0.3, grid),
        ("BACKGROUND", (5, 1), (-1, -1), colors.HexColor("#" + FILL_IN)),
        ("ALIGN", (4, 1), (6, -1), "CENTER")]))
    story.append(table)
    f_name, f_sign, f_date = t["sign_fields"]
    sign = Table([list(t["sign"]),
                  [f"{f_name}: {p.mdl_prepared_by or tr.created_by_name or ''}", f"{f_name}:"],
                  [f"{f_sign}:"] * 2, [f"{f_date}:"] * 2],
                 colWidths=[136 * mm] * 2, rowHeights=[6 * mm, 8 * mm, 10 * mm, 8 * mm])
    sign.setStyle(TableStyle(
        [("FONT", (0, 0), (-1, -1), regular, 8), ("FONT", (0, 0), (-1, 0), bold, 8),
         ("BACKGROUND", (0, 0), (-1, 0), navy), ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
         ("VALIGN", (0, 1), (-1, -1), "BOTTOM"),
         ("TEXTCOLOR", (0, 1), (-1, -1), colors.HexColor("#595959"))]
        + [("BOX", (i, 0), (i, -1), 0.5, grid) for i in range(2)]))
    codes = "；".join(_code_labels(ctx["codes"], ctx["lang"])) if ctx["lang"] == "zh" else \
        "; ".join(_code_labels(ctx["codes"], ctx["lang"]))
    story += [Spacer(1, 3 * mm), KeepTogether([
        Paragraph(f"<b>{escape(t['codes'])}</b>: {escape(codes)}", small),
        Paragraph(f"<b>{escape(t['reply_ref'])}</b>: ______________________", small),
        Spacer(1, 4 * mm), sign])]
    doc.build(story, canvasmaker=mx.numbered_canvas(regular, ctx["footer"], t["page"]))
    return buffer.getvalue()


