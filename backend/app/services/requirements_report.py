"""合同外新增要求清单（Excel）：要求类别为"客户要求"的文件种类，
带提出日期、要求依据、接受情况、变更单号和完成情况，可以直接拿去谈变更或费用。
"""

import io
from collections import defaultdict
from datetime import date, datetime

from openpyxl import Workbook
from openpyxl.styles import Alignment, Font
from sqlalchemy import select
from sqlalchemy.orm import Session

from app.models import DocumentType, DocumentTypeOrigin, Milestone
from app.services import mdl_export as mx
from app.services.deliverable_query import Filters, Item, _number, load_items, stats
from app.services.projects import get_project

TEXT = {
    "en": {"title": "CLIENT-REQUESTED ADDITIONS (OUTSIDE CONTRACT)", "project": "Project",
           "as_of": "As of", "sheet": "Client Requests",
           "columns": ("No.", "Document Title", "Milestone", "Requested", "Request Ref",
                       "Acceptance", "Acceptance Ref", "Variation Ref", "Changed", "Change Ref",
                       "Applicable", "Approved", "Completion"),
           "acceptance": {"pending": "Pending", "accepted": "Accepted", "declined": "Declined"},
           "footer": "Generated by {p}  ·  {code}  ·  {at}  ·  System-generated document"},
    "zh": {"title": "合同外新增要求清单", "project": "项目", "as_of": "统计日期", "sheet": "新增要求",
           "columns": ("编号", "文件名称", "里程碑", "提出日期", "要求依据", "接受情况", "接受依据",
                       "变更单号", "变更日期", "变更依据", "应交数", "已批准", "完成率"),
           "acceptance": {"pending": "待确认", "accepted": "接受", "declined": "不接受"},
           "footer": "{p} 系统生成  ·  {code}  ·  {at}  ·  系统生成文件"},
}


def export(session: Session, project_id: int, *, lang: str = "en", today: date | None = None
           ) -> bytes:
    project = get_project(session, project_id)
    t = TEXT[lang]
    rows = session.execute(
        select(DocumentType, Milestone).join(Milestone, Milestone.id == DocumentType.milestone_id)
        .where(DocumentType.project_id == project_id, DocumentType.active,
               DocumentType.origin == DocumentTypeOrigin.CLIENT)).all()
    rows.sort(key=lambda r: (_number(r[1].number), _number(r[0].submittal_no)))
    by_doc: dict[int, list[Item]] = defaultdict(list)
    for it in load_items(session, project_id, Filters(origins=[DocumentTypeOrigin.CLIENT.value]),
                         today=today):
        by_doc[it.document_type_id].append(it)

    wb = Workbook()
    ws = wb.active
    ws.title = t["sheet"]
    ws["A1"] = t["title"]
    ws["A1"].font = Font(size=16, bold=True, color=mx.NAVY)
    ws["A2"], ws["B2"] = t["project"], f"{project.name} ({project.code})"
    ws["A3"], ws["B3"] = t["as_of"], today or date.today()
    ws["B3"].number_format, ws["B3"].alignment = "yyyy-mm-dd", Alignment(horizontal="left")
    for c in ("A2", "A3"):
        ws[c].font = Font(bold=True, color="595959")
    header = 5
    mx._header_cells(ws, header, t["columns"], (8, 36, 10, 12, 22, 12, 22, 16, 12, 22, 11, 10, 11))
    for r, (doc, ms) in enumerate(rows, start=header + 1):
        s = stats(by_doc.get(doc.id, []))
        values = (doc.submittal_no, doc.name, ms.code, doc.required_date, doc.basis,
                  t["acceptance"].get(doc.acceptance.value if doc.acceptance else "pending"),
                  doc.acceptance_ref, doc.variation_ref, doc.changed_date, doc.change_ref,
                  s["applicable"], s["approved"], s["completion"])
        for col, v in enumerate(values, start=1):
            c = ws.cell(r, col, v)
            c.border = mx.BOX
            c.alignment = Alignment(vertical="center", wrap_text=col in (2, 5, 7, 10))
            if isinstance(v, date):
                c.number_format = "yyyy-mm-dd"
        ws.cell(r, 13).number_format = "0%"
    last = header + len(rows)
    ws.auto_filter.ref = f"A{header}:M{max(last, header)}"
    ws.freeze_panes = ws.cell(header + 1, 1)
    ws.page_setup.orientation, ws.page_setup.paperSize = "landscape", ws.PAPERSIZE_A4
    ws.page_setup.fitToWidth, ws.page_setup.fitToHeight = 1, 0
    ws.sheet_properties.pageSetUpPr.fitToPage = True
    ws.oddFooter.left.text = t["footer"].format(p=mx.PLATFORM, code=project.code,
                                                at=f"{datetime.now():%Y-%m-%d %H:%M}")
    ws.oddFooter.left.size = 7
    wb.properties.creator = f"{mx.PLATFORM} (system generated)"
    buffer = io.BytesIO()
    wb.save(buffer)
    return buffer.getvalue()
