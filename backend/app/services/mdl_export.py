def _report_for(session: Session, project_id: int, lang: str, rev_no: int | None,
                today: date | None = None) -> Report:
    versions = mdl_versions.list_versions(session, project_id)
    if rev_no is None:  # 当前结构，不记版本
        snapshot = mdl_versions.build_snapshot(session, project_id)
        previous = versions[-1].snapshot if versions else None
        return build_report(session, project_id, snapshot, lang=lang, rev_label=None,
                            previous=previous, versions=versions, today=today)
    version = mdl_versions.get_version(session, project_id, rev_no)
    previous = (mdl_versions.get_version(session, project_id, rev_no - 1).snapshot
                if rev_no > 0 else None)
    return build_report(session, project_id, version.snapshot, lang=lang,
                        rev_label=mdl_versions.label(rev_no), previous=previous,
                        versions=[v for v in versions if v.rev_no <= rev_no], today=today)


def export_current(session: Session, project_id: int, *, lang: str = "en", fmt: str = "xlsx",
                   today: date | None = None) -> bytes:
    """内部预览：按当前结构导出，标"草稿"，不记版本。"""
    return render(_report_for(session, project_id, lang, None, today), fmt)


def export_version(session: Session, project_id: int, rev_no: int, *, lang: str = "en",
                   fmt: str = "xlsx", today: date | None = None) -> bytes:
    """导出某个版本：结构用那一版的快照，状态用当前的。"""
    return render(_report_for(session, project_id, lang, rev_no, today), fmt)


def issue(session: Session, project_id: int, actor: Actor, *, lang: str = "en", fmt: str = "xlsx",
          description: str | None = None) -> tuple[bytes, MdlVersion, bool]:
    """发给客户：记一个版本再导出；结构和上一版相比没变时沿用上一版的版本号。
    返回 (文件, 版本, 是否新版本)。"""
    try:
        version = mdl_versions.freeze_version(session, project_id, actor, description=description)
        new = True
    except Conflict as exc:
        if exc.code != "mdl_version.no_changes":
            raise
        version = mdl_versions.list_versions(session, project_id)[-1]
        new = False
        # 沿用上一版再发一次也要留记录：之后判断设备、模块"客户见过没有"按最近一次发出的时间
        from app.models import ChangeAction
        from app.services.history import record_summary

        record_summary(session, project_id=project_id, entity_type="mdl_versions", entity_id=str(version.id),
                       action=ChangeAction.UPDATE, changes={"reissued": [None, f"Rev.{version.rev_no}"]},
                       actor=actor, reason=description or f"结构没变，沿用 Rev.{version.rev_no} 再次发出")
    return export_version(session, project_id, version.rev_no, lang=lang, fmt=fmt), version, new


