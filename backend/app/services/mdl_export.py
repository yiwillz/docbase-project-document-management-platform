@dataclass
class Row:
    no: str | None
    title: str
    category: str | None
    status_text: str
    status_key: str
    due: date | None = None
    submitted: date | None = None
    status_date: date | None = None
    remarks: str | None = None
    outstanding: str | None = None  # 待交说明（红字）
    chg: str = ""
    key: str | None = None          # "D:<应交项 id>"：状态和日期可改
    remarks_key: str | None = None  # "T:<种类 id>" / "P:<种类 id>:<模块 id>"：备注可改
    sub: bool = False               # 模块子行


@dataclass
class Group:
    code: str
    name: str | None
    due: date | None
    rows: list[Row] = field(default_factory=list)
    done: int = 0
    total: int = 0


@dataclass
class Report:
    project: Project
    lang: str
    rev_label: str | None
    issue_date: date | None
    generated_at: datetime
    groups: list[Group] = field(default_factory=list)
    history: list[tuple[str, date, str | None]] = field(default_factory=list)
    outstanding: list[tuple[str, str, str, str, str, str]] = field(default_factory=list)

    @property
    def t(self) -> dict[str, Any]:
        return TEXT[self.lang]

    @property
    def doc_no(self) -> str:
        return self.project.mdl_doc_no or f"{self.project.code}-MDL"

    def footer(self) -> str:
        return self.t["footer"].format(p=PLATFORM, doc=self.doc_no,
                                       rev=self.rev_label or self.t["draft"],
                                       at=f"{self.generated_at:%Y-%m-%d %H:%M}")


def _date(value: Any) -> date | None:
    if value is None or isinstance(value, date):
        return value
    return date.fromisoformat(value)


def _doc_remarks(doc: DocumentType | None, t: dict[str, Any]) -> str | None:
    """种类行的备注：MDL 备注；不接受的客户要求没写备注时，自动写明不接受及依据。"""
    if doc is None:
        return None
    if doc.mdl_remarks:
        return doc.mdl_remarks
    if doc.acceptance is Acceptance.DECLINED:
        return t["declined"].format(ref=doc.acceptance_ref or "")
    return None


def _status_key(d: Deliverable, due: date | None, today: date) -> str:
    """due 为种类（或里程碑）的截止日；应交项自己设了截止日的以它为准。"""
    actual, _ = deliverable_svc.effective_due(d.due_date, due, None)
    if deliverable_svc.is_overdue(d.status, actual, today):
        return "O"  # 过了截止日还没提交
    return KEY_OF[d.status]


def build_report(session: Session, project_id: int, snapshot: dict[str, Any], *, lang: str,
                 rev_label: str | None, previous: dict[str, Any] | None,
                 versions: list[MdlVersion], today: date | None = None) -> Report:
    """按结构快照 + 当前应交项（状态）组织报表数据。previous 为上一版快照（标 NEW / CHG）。"""
    today = today or date.today()
    t = TEXT[lang]
    project = get_project(session, project_id)
    report = Report(project=project, lang=lang, rev_label=rev_label,
                    issue_date=today if rev_label else None, generated_at=datetime.now())
    report.history = [(mdl_versions.label(v.rev_no), v.frozen_at.date(), v.description)
                      for v in versions]

    diff = mdl_versions.diff_snapshots(previous, snapshot) if previous else None
    added = {d["id"] for d in diff["document_types"]["added"]} if diff else set()
    changed = {d["id"] for d in diff["document_types"]["modified"]} if diff else set()

    doc_ids = [int(k) for k in snapshot["document_types"]]
    docs = {d.id: d for d in session.scalars(
        select(DocumentType).where(DocumentType.id.in_(doc_ids)))} if doc_ids else {}
    partitions = {(p.document_type_id, p.module_id): p for p in session.scalars(
        select(DocumentTypeModule).where(DocumentTypeModule.document_type_id.in_(doc_ids)))
    } if doc_ids else {}
    module_ids = {m.name: m.id for m in session.scalars(
        select(Module).where(Module.project_id == project_id))}
    equipment = {e.id: e for e in session.scalars(
        select(Equipment).where(Equipment.project_id == project_id))}
    type_modules: dict[int, set[int]] = defaultdict(set)
    for module_id, type_id in session.execute(
            select(ModuleEquipmentType.module_id, ModuleEquipmentType.equipment_type_id)
            .where(ModuleEquipmentType.active)):
        type_modules[type_id].add(module_id)

    whole: dict[int, Deliverable] = {}
    per_module: dict[tuple[int, int], Deliverable] = {}
    per_equipment: dict[int, list[Deliverable]] = defaultdict(list)
    if doc_ids:
        for d in session.scalars(select(Deliverable).where(
                Deliverable.document_type_id.in_(doc_ids), Deliverable.obsolete.is_(False))):
            if d.equipment_id is not None:
                per_equipment[d.document_type_id].append(d)
            elif d.module_id is not None:
                per_module[(d.document_type_id, d.module_id)] = d
            else:
                whole[d.document_type_id] = d

    def summary(items: list[Deliverable]) -> tuple[str, str]:
        counted = [d for d in items if d.status is not S.NOT_APPLICABLE]
        if not items:
            return t["no_equipment"], "N"
        if not counted:
            return t["status"]["X"], "X"
        ok = sum(d.status is S.APPROVED for d in counted)
        key = "A" if ok == len(counted) else "R" if ok else "N"
        return t["approved_of"].format(a=ok, t=len(counted)), key

    for ms_id, ms in sorted(snapshot["milestones"].items(), key=lambda kv: int(kv[1]["number"])):
        group = Group(code=ms["code"], name=ms.get("name"), due=_date(ms.get("due_date")))
        items = sorted(((int(k), v) for k, v in snapshot["document_types"].items()
                        if str(v["milestone_id"]) == ms_id),
                       key=lambda kv: int(kv[1]["submittal_no"].rsplit(".", 1)[1]))
        for doc_id, sd in items:
            doc = docs.get(doc_id)
            due = _date(sd.get("due_date")) or group.due
            chg = "NEW" if doc_id in added else "CHG" if doc_id in changed else ""
            base = dict(no=sd["submittal_no"], title=sd["name"], category=sd.get("category"),
                        due=due, chg=chg, remarks=_doc_remarks(doc, t),
                        remarks_key=f"T:{doc_id}" if doc else None)
            modules = sd.get("modules") or []

            if sd.get("per_equipment"):
                eqs = per_equipment.get(doc_id, [])
                text, key = summary(eqs)
                missing: dict[str, int] = defaultdict(int)
                for d in sorted(eqs, key=lambda x: (equipment[x.equipment_id].sort_order,
                                                    x.equipment_id)):
                    if d.status in (S.APPROVED, S.NOT_APPLICABLE):
                        continue
                    e = equipment[d.equipment_id]
                    mods = type_modules.get(e.equipment_type_id, set())
                    name = next((m for m in modules if module_ids.get(m) in mods), t["other"])
                    missing[name] += 1
                    report.outstanding.append((sd["submittal_no"], sd["name"], name, e.tag, e.name,
                                               t["status"][_status_key(d, due, today)]))
                out = ", ".join(f"{m} {n}" for m, n in missing.items())
                group.rows.append(Row(**base, status_text=text, status_key=key,
                                      outstanding=t["outstanding"].format(items=out) if out else None))
                complete = key in ("A", "X")
            elif modules:
                subs = [(m, per_module.get((doc_id, module_ids.get(m)))) for m in modules]
                text, key = summary([d for _, d in subs if d])
                group.rows.append(Row(**base, status_text=text, status_key=key))
                for name, d in subs:
                    part = partitions.get((doc_id, module_ids.get(name)))
                    sk = _status_key(d, due, today) if d else "N"
                    group.rows.append(Row(
                        no=None, title=name, category=None, status_text=t["status"][sk],
                        status_key=sk, due=d.due_date if d else None,
                        submitted=d.submitted_date if d else None,
                        status_date=d.status_date if d else None,
                        remarks=part.mdl_remarks if part else None,
                        key=f"D:{d.id}" if d else None,
                        remarks_key=f"P:{doc_id}:{module_ids[name]}" if part else None, sub=True))
                complete = key in ("A", "X")
            else:
                d = whole.get(doc_id)
                sk = _status_key(d, due, today) if d else "N"
                if d is not None and d.due_date is not None:
                    base["due"] = d.due_date  # 应交项自己的截止日
                group.rows.append(Row(**base, status_text=t["status"][sk], status_key=sk,
                                      submitted=d.submitted_date if d else None,
                                      status_date=d.status_date if d else None,
                                      key=f"D:{d.id}" if d else None))
                complete = sk in ("A", "X")
            group.total += 1
            group.done += complete
        report.groups.append(group)
    return report


