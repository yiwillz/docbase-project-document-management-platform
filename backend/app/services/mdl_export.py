def _cjk_fonts() -> tuple[str, str]:
    registered = pdfmetrics.getRegisteredFontNames()
    if "CJK" in registered:
        return "CJK", "CJK-Bold"
    for regular, bold in _CJK_FILES:
        if Path(regular).exists() and Path(bold).exists():
            try:
                pdfmetrics.registerFont(TTFont("CJK", regular, subfontIndex=0))
                pdfmetrics.registerFont(TTFont("CJK-Bold", bold, subfontIndex=0))
                return "CJK", "CJK-Bold"
            except Exception:  # noqa: BLE001  字体文件不能用就试下一个
                continue
    # 兜底：reportlab 自带的 CID 字体，不嵌入，阅读器要有亚洲字体包才显示
    if _CJK_FONT not in registered:
        pdfmetrics.registerFont(UnicodeCIDFont(_CJK_FONT))
    return _CJK_FONT, _CJK_FONT


def _fonts(lang: str) -> tuple[str, str]:
    """（常规, 粗体）字体；中文优先嵌入系统里的中文字体。"""
    if lang == "zh":
        return _cjk_fonts()
    return "Helvetica", "Helvetica-Bold"


def numbered_canvas(font: str, footer: str, page_text: str, pagesize=None) -> type:
    """PDF 画布：两遍渲染，每页页脚写系统生成标识和"第 n 页 / 共 m 页"（传送单、关闭清单共用）。"""
    grid = colors.HexColor("#" + GRID)
    w, _ = pagesize or landscape(A4)

    class NumberedCanvas(rl_canvas.Canvas):
        def __init__(self, *args, **kwargs):
            super().__init__(*args, **kwargs)
            self._saved = []

        def showPage(self):
            self._saved.append(dict(self.__dict__))
            self._startPage()

        def save(self):
            total = len(self._saved)
            for state in self._saved:
                self.__dict__.update(state)
                self.setStrokeColor(grid)
                self.line(12 * mm, 10 * mm, w - 12 * mm, 10 * mm)
                self.setFont(font, 6.5)
                self.setFillColor(colors.HexColor("#7F7F7F"))
                self.drawString(12 * mm, 6 * mm, footer)
                self.drawRightString(w - 12 * mm, 6 * mm,
                                     page_text.format(n=self._pageNumber, m=total))
                super().showPage()
            super().save()

    return NumberedCanvas


def render_pdf(report: Report) -> bytes:
    t = report.t
    p = report.project
    regular, bold = _fonts(report.lang)
    navy, grid = colors.HexColor("#" + NAVY), colors.HexColor("#" + GRID)
    small = ParagraphStyle("s", fontName=regular, fontSize=7.5, leading=9)
    footer, page_text = report.footer(), t["page"]

    NumberedCanvas = numbered_canvas(regular, footer, page_text)

    buffer = io.BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=landscape(A4), leftMargin=12 * mm, rightMargin=12 * mm,
                            topMargin=12 * mm, bottomMargin=14 * mm,
                            title=f"{report.doc_no} {t['title']} {report.rev_label or t['draft']}",
                            author=f"{PLATFORM} (system generated)")
    story: list[Any] = [Paragraph(f"<font size=16 color='#{NAVY}'><b>{escape(t['title'])}</b></font>",
                                  ParagraphStyle("t", parent=small, fontName=bold, leading=20,
                                                 spaceAfter=3 * mm))]
    info = (f"{p.name} ({p.code})", p.client_name or "", p.contractor_name or "")
    meta = (report.doc_no, report.rev_label or t["draft"],
            f"{report.issue_date:%Y-%m-%d}" if report.issue_date else "")
    info_t = Table([[k1, v1, k2, v2] for k1, v1, k2, v2 in zip(t["info"], info, t["meta"], meta, strict=True)],
                   colWidths=[25 * mm, 120 * mm, 30 * mm, 98 * mm])
    info_t.setStyle(TableStyle([
        ("FONT", (0, 0), (-1, -1), regular, 8.5), ("FONT", (0, 0), (0, -1), bold, 8.5),
        ("FONT", (2, 0), (2, -1), bold, 8.5),
        ("TEXTCOLOR", (0, 0), (0, -1), colors.HexColor("#595959")),
        ("TEXTCOLOR", (2, 0), (2, -1), colors.HexColor("#595959")),
        ("LINEBELOW", (0, -1), (-1, -1), 1.2, navy), ("BOTTOMPADDING", (0, 0), (-1, -1), 2)]))
    story += [info_t, Spacer(1, 5 * mm)]

    data: list[list[Any]] = [list(t["columns"])]
    style = [("FONT", (0, 0), (-1, 0), bold, 7.5), ("BACKGROUND", (0, 0), (-1, 0), navy),
             ("TEXTCOLOR", (0, 0), (-1, 0), colors.white), ("ALIGN", (0, 0), (-1, 0), "CENTER"),
             ("FONT", (0, 1), (-1, -1), regular, 7.5), ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
             ("GRID", (0, 0), (-1, -1), 0.3, grid),
             ("ALIGN", (3, 1), (6, -1), "CENTER"), ("ALIGN", (8, 1), (8, -1), "CENTER")]
    fmt = lambda d: f"{d:%Y-%m-%d}" if d else ""  # noqa: E731
    for g in report.groups:
        heading = t["group"].format(code=g.code, name=g.name or "",
                                    due=f"{g.due:%Y-%m-%d}" if g.due else "—",
                                    done=g.done, total=g.total)
        data.append([Paragraph(f"<b>{escape(heading)}</b>",
                               ParagraphStyle("m", parent=small, fontName=bold, textColor=navy))]
                    + [""] * 8)
        i = len(data) - 1
        style += [("SPAN", (0, i), (-1, i)), ("BACKGROUND", (0, i), (-1, i), colors.HexColor("#" + LIGHT))]
        for row in g.rows:
            if row.remarks:
                remarks = escape(row.remarks)
            elif row.outstanding:
                remarks = f"<font color='#9C0006'>{escape(row.outstanding)}</font>"
            else:
                remarks = ""
            title = ("&nbsp;" * 6 + escape(row.title)) if row.sub else escape(row.title)
            data.append([row.no or "", Paragraph(title, small), row.category or "", row.status_text,
                         fmt(row.due), fmt(row.submitted), fmt(row.status_date),
                         Paragraph(remarks, small), row.chg])
            i = len(data) - 1
            fill, font = COLORS[row.status_key]
            style += [("BACKGROUND", (3, i), (3, i), colors.HexColor("#" + fill)),
                      ("TEXTCOLOR", (3, i), (3, i), colors.HexColor("#" + font)),
                      ("FONT", (3, i), (3, i), bold, 7.5)]
            if row.chg:
                style += [("TEXTCOLOR", (8, i), (8, i), colors.HexColor("#C00000")),
                          ("FONT", (8, i), (8, i), bold, 7)]
    main = Table(data, colWidths=[w * mm for w in (12, 78, 26, 30, 19, 19, 19, 60, 10)], repeatRows=1)
    main.setStyle(TableStyle(style))
    story.append(main)

    legend = Table([[Paragraph(f"<b>{escape(t['status'][k])}</b>",
                               ParagraphStyle(f"l{k}", parent=small, fontName=bold, alignment=1,
                                              textColor=colors.HexColor("#" + COLORS[k][1])))
                     for k in LEGEND]], colWidths=[30 * mm] * len(LEGEND), hAlign="LEFT")
    legend.setStyle(TableStyle([("BACKGROUND", (i, 0), (i, 0), colors.HexColor("#" + COLORS[k][0]))
                                for i, k in enumerate(LEGEND)] + [("GRID", (0, 0), (-1, -1), 0.3, grid)]))
    names = (p.mdl_prepared_by, p.mdl_checked_by, p.mdl_approved_by)
    f_name, f_sign, f_date = t["sign_fields"]
    sign = Table([list(t["sign"]), [f"{f_name}: {n or ''}" for n in names],
                  [f"{f_sign}:"] * 3, [f"{f_date}:"] * 3],
                 colWidths=[91 * mm] * 3, rowHeights=[6 * mm, 8 * mm, 10 * mm, 8 * mm])
    sign.setStyle(TableStyle(
        [("FONT", (0, 0), (-1, -1), regular, 8), ("FONT", (0, 0), (-1, 0), bold, 8),
         ("BACKGROUND", (0, 0), (-1, 0), navy), ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
         ("VALIGN", (0, 1), (-1, -1), "BOTTOM"),
         ("TEXTCOLOR", (0, 1), (-1, -1), colors.HexColor("#595959"))]
        + [("BOX", (i, 0), (i, -1), 0.5, grid) for i in range(3)]))
    story += [Spacer(1, 4 * mm), KeepTogether([
        Paragraph(f"<b>{escape(t['legend'])}</b>", ParagraphStyle("lg", parent=small, fontName=bold)),
        Spacer(1, 1 * mm), legend, Paragraph(escape(t["chg_note"]), small), Spacer(1, 5 * mm), sign])]

    head = [("FONT", (0, 0), (-1, 0), bold, 8), ("BACKGROUND", (0, 0), (-1, 0), navy),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white), ("FONT", (0, 1), (-1, -1), regular, 8),
            ("GRID", (0, 0), (-1, -1), 0.3, grid)]
    h2 = ParagraphStyle("h2", parent=small, fontName=bold, fontSize=11, leading=14, textColor=navy)
    history_rows = [[r, f"{d:%Y-%m-%d}", Paragraph(escape(desc or ""), small)]
                    for r, d, desc in report.history] or [[t["none"], "", ""]]
    hist = Table([list(t["history_cols"])] + history_rows,
                 colWidths=[25 * mm, 25 * mm, 150 * mm], hAlign="LEFT")
    hist.setStyle(TableStyle(head))
    rows = [list(t["out_cols"])] + ([list(item) for item in report.outstanding]
                                    or [[t["none"], "", "", "", "", ""]])
    out = Table(rows, colWidths=[14 * mm, 70 * mm, 30 * mm, 30 * mm, 60 * mm, 35 * mm],
                repeatRows=1, hAlign="LEFT")
    status_key = {v: k for k, v in t["status"].items()}
    out.setStyle(TableStyle(head + [("FONT", (0, 1), (-1, -1), regular, 7.5)] + [
        ("BACKGROUND", (5, i), (5, i), colors.HexColor("#" + COLORS[status_key[item[5]]][0]))
        for i, item in enumerate(report.outstanding, start=1)]))
    story += [PageBreak(), Paragraph(escape(t["history"]), h2), Spacer(1, 2 * mm), hist,
              Spacer(1, 6 * mm), Paragraph(escape(t["out_title"]), h2), Spacer(1, 2 * mm), out]
    doc.build(story, canvasmaker=NumberedCanvas)
    return buffer.getvalue()


def render(report: Report, fmt: str) -> bytes:
    return render_pdf(report) if fmt == "pdf" else render_excel(report)


