@dataclass
class Issue:
    code: str
    message: str
    row: int | None = None


def _cell_date(value: Any) -> date | None:
    if value is None or value == "":
        return None
    if isinstance(value, datetime):
        return value.date()
    if isinstance(value, date):
        return value
    text = str(value).strip()
    for pattern in ("%Y-%m-%d", "%Y/%m/%d", "%Y.%m.%d"):
        try:
            return datetime.strptime(text, pattern).date()
        except ValueError:
            pass
    raise ValueError(f"日期格式不对：{text}")


def _cell_text(value: Any) -> str | None:
    if value is None:
        return None
    text = str(value).strip()
    return text or None


def _iso(value: date | None) -> str | None:
    return value.isoformat() if value else None


def parse_return(session: Session, project_id: int, data: bytes) -> dict[str, Any]:
    """解析导回的 MDL Excel，和数据库比对。返回 {ok, changes, errors, warnings}（不写入）。"""
    errors: list[Issue] = []
    warnings: list[Issue] = []

    def fail(issue_: Issue) -> dict[str, Any]:
        return {"ok": False, "changes": [], "warnings": [], "errors": [issue_.__dict__]}

    try:
        wb = load_workbook(io.BytesIO(data), data_only=True)
    except Exception as exc:
        return fail(Issue("mdl_import.unreadable", f"无法读取 Excel：{exc}"))
    meta = ({str(r[0].value): r[1].value for r in wb["_meta"].iter_rows(max_col=2)}
            if "_meta" in wb.sheetnames else {})
    if meta.get("format") != FORMAT or int(meta.get("version") or 0) != FORMAT_VERSION:
        return fail(Issue("mdl_import.not_platform_file",
                          "这不是平台当前格式导出的 MDL（只认平台导出的文件）"))
    if int(meta.get("project_id") or 0) != project_id:
        return fail(Issue("mdl_import.other_project",
                          f"这是另一个项目（{meta.get('project_code')}）导出的 MDL"))

    labels = {v: k for k, v in TEXT[meta.get("lang") or "en"]["status"].items()}
    ws = wb["MDL"]
    deliverables = {d.id: d for d in session.scalars(
        select(Deliverable).where(Deliverable.project_id == project_id))}
    docs = {d.id: d for d in session.scalars(
        select(DocumentType).where(DocumentType.project_id == project_id))}
    partitions = {(p.document_type_id, p.module_id): p for p in session.scalars(
        select(DocumentTypeModule).where(DocumentTypeModule.document_type_id.in_(list(docs))))
    } if docs else {}

    changes = []
    for r in range(int(meta["header_row"]) + 1, int(meta["last_row"]) + 1):
        key, rkey = _cell_text(ws.cell(r, C_KEY).value), _cell_text(ws.cell(r, C_RKEY).value)
        status_text = _cell_text(ws.cell(r, C_STATUS).value)
        label = " ".join(filter(None, [_cell_text(ws.cell(r, C_NO).value),
                                       _cell_text(ws.cell(r, C_TITLE).value)]))
        if key and key.startswith("D:"):
            d = deliverables.get(int(key[2:]))
            if d is None:
                warnings.append(Issue("mdl_import.unknown_row", "找不到这一行对应的应交项，已跳过", r))
                continue
            if status_text not in labels:
                errors.append(Issue("mdl_import.bad_status", f"状态\"{status_text}\"不认识", r))
                continue
            # "逾期"只是显示，对应的状态仍是未提交
            new_status = STATUS_OF_KEY.get(labels[status_text], S.NOT_SUBMITTED)
            row_changes: dict[str, list[Any]] = {}
            if new_status != d.status:
                row_changes["status"] = [d.status.value, new_status.value]
            try:
                for col, f in ((C_SDATE, "status_date"), (C_SUB, "submitted_date")):
                    new = _cell_date(ws.cell(r, col).value)
                    if new != getattr(d, f):
                        row_changes[f] = [_iso(getattr(d, f)), _iso(new)]
            except ValueError as exc:
                errors.append(Issue("mdl_import.bad_date", str(exc), r))
                continue
            if row_changes:
                changes.append({"row": r, "target": "deliverable", "id": d.id, "label": label,
                                "changes": row_changes})
        elif (key or rkey) and status_text != _cell_text(ws.cell(r, C_ORIG_STATUS).value):
            warnings.append(Issue("mdl_import.readonly_changed",
                                  "这是汇总行，状态改动不会导入（单台设备的状态请在平台里改）", r))
        remarks = _cell_text(ws.cell(r, C_REM).value)
        if rkey and remarks != _cell_text(ws.cell(r, C_ORIG_REM).value):
            target, old = _remarks_target(rkey, docs, partitions)
            if target is not None and remarks != old:
                kind = "document_type" if rkey.startswith("T:") else "partition"
                changes.append({"row": r, "target": kind, "key": rkey, "label": label,
                                "changes": {"mdl_remarks": [old, remarks]}})
    return {"ok": not errors, "changes": changes, "errors": [e.__dict__ for e in errors],
            "warnings": [w.__dict__ for w in warnings], "revision": meta.get("revision")}


def _remarks_target(rkey: str, docs: dict, partitions: dict):
    parts = rkey.split(":")
    if parts[0] == "T":
        doc = docs.get(int(parts[1]))
        return (doc, doc.mdl_remarks) if doc else (None, None)
    if parts[0] == "P":
        part = partitions.get((int(parts[1]), int(parts[2])))
        return (part, part.mdl_remarks) if part else (None, None)
    return None, None


def apply_return(session: Session, project_id: int, changes: list[dict[str, Any]], actor: Actor,
                 *, source: str | None = None) -> dict[str, int]:
    """把导回比对出的改动写入：应交项逐个修改（留痕、发事件），备注写回文件种类 / 分区。"""
    reason = f"MDL 导回（{source}）" if source else "MDL 导回"
    counts = {"deliverables": 0, "remarks": 0}
    status_changes = []
    for change in changes:
        values = {f: v[1] for f, v in change["changes"].items()}
        if change["target"] == "deliverable":
            for f in ("status_date", "submitted_date"):
                if f in values:
                    values[f] = _date(values[f])
            d = deliverable_svc.update_deliverable(session, project_id, change["id"], values, actor,
                                                   reason=reason)
            counts["deliverables"] += 1
            if "status" in values:
                status_changes.append({"deliverable_id": d.id, "status": d.status,
                                       "status_date": d.status_date,
                                       "submitted_date": d.submitted_date})
        elif change["target"] == "document_type":
            structure_svc.update_document_type(session, project_id, int(change["key"][2:]),
                                               values, actor, reason=reason)
            counts["remarks"] += 1
        else:
            _, doc_id, module_id = change["key"].split(":")
            structure_svc.update_partition(session, project_id, int(doc_id), int(module_id),
                                           values, actor, reason=reason)
            counts["remarks"] += 1
    # 客户在 MDL 上给的结论，同时记成客户回复（找不到传送单的自动补记一张）
    transmittal_svc.record_mdl_return(session, project_id, status_changes, actor, source_name=source)
    return counts
