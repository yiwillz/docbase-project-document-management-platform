THIN = Side(style="thin", color=GRID)
BOX = Border(left=THIN, right=THIN, top=THIN, bottom=THIN)


def _header_cells(ws, row: int, titles, widths=None) -> None:
    for i, title in enumerate(titles, start=1):
        c = ws.cell(row, i, title)
        c.font, c.fill = Font(bold=True, color="FFFFFF"), PatternFill("solid", fgColor=NAVY)
        c.alignment, c.border = Alignment(horizontal="center", vertical="center"), BOX
        if widths:
            ws.column_dimensions[get_column_letter(i)].width = widths[i - 1]


def _print_setup(ws, report: Report) -> None:
    ws.page_setup.orientation, ws.page_setup.paperSize = "landscape", ws.PAPERSIZE_A4
    ws.page_setup.fitToWidth, ws.page_setup.fitToHeight = 1, 0
    ws.sheet_properties.pageSetUpPr.fitToPage = True
    ws.oddFooter.left.text, ws.oddFooter.left.size = report.footer(), 7
    ws.oddFooter.right.text, ws.oddFooter.right.size = report.t["excel_page"], 7


def render_excel(report: Report) -> bytes:
    t = report.t
    p = report.project
    wb = Workbook()
    ws = wb.active
    ws.title = "MDL"
    widths = (7, 40, 14, 18, 11, 11, 11, 38, 6)

    ws.merge_cells("A1:E1")
    ws["A1"] = t["title"]
    ws["A1"].font = Font(size=16, bold=True, color=NAVY)
    info = (f"{p.name} ({p.code})", p.client_name or "", p.contractor_name or "")
    meta = (report.doc_no, report.rev_label or t["draft"], report.issue_date)
    for r, (k1, v1, k2, v2) in enumerate(zip(t["info"], info, t["meta"], meta, strict=True), start=2):
        ws.cell(r, 1, k1).font = Font(bold=True, color="595959")
        ws.merge_cells(start_row=r, start_column=2, end_row=r, end_column=3)
        ws.cell(r, 2, v1)
        ws.cell(r, 7, k2).font = Font(bold=True, color="595959")
        ws.merge_cells(start_row=r, start_column=8, end_row=r, end_column=9)
        c = ws.cell(r, 8, v2)
        c.alignment = Alignment(horizontal="left")
        if isinstance(v2, date):
            c.number_format = "yyyy-mm-dd"
    for col in range(1, 10):
        ws.cell(4, col).border = Border(bottom=Side(style="medium", color=NAVY))

    header = 6
    _header_cells(ws, header, t["columns"], widths)
    dv = DataValidation(type="list", allow_blank=True,
                        formula1='"' + ",".join(t["status"][k] for k in "ARSCNX") + '"')
    ws.add_data_validation(dv)
    r = header
    for g in report.groups:
        r += 1
        ws.merge_cells(start_row=r, start_column=1, end_row=r, end_column=9)
        c = ws.cell(r, 1, t["group"].format(code=g.code, name=g.name or "",
                                            due=f"{g.due:%Y-%m-%d}" if g.due else "—",
                                            done=g.done, total=g.total))
        c.font, c.fill = Font(bold=True, color=NAVY), PatternFill("solid", fgColor=LIGHT)
        for row in g.rows:
            r += 1
            remarks = row.remarks or row.outstanding
            values = (row.no, ("    " if row.sub else "") + row.title, row.category, row.status_text,
                      row.due, row.submitted, row.status_date, remarks, row.chg)
            for col, v in enumerate(values, start=1):
                c = ws.cell(r, col, v)
                c.border = BOX
                c.alignment = Alignment(vertical="center", wrap_text=col in (C_TITLE, C_REM))
                if isinstance(v, date):
                    c.number_format, c.alignment = "yyyy-mm-dd", Alignment(horizontal="center")
            fill, font = COLORS[row.status_key]
            sc = ws.cell(r, C_STATUS)
            sc.fill, sc.font = PatternFill("solid", fgColor=fill), Font(bold=True, color=font)
            sc.alignment = Alignment(horizontal="center")
            if row.chg:
                ws.cell(r, C_CHG).font = Font(bold=True, color="C00000")
                ws.cell(r, C_CHG).alignment = Alignment(horizontal="center")
            if row.outstanding and not row.remarks:
                ws.cell(r, C_REM).font = Font(color="9C0006")
            if row.sub:
                ws.cell(r, C_TITLE).font = Font(color="595959")
            if row.key:
                dv.add(sc)
            ws.cell(r, C_KEY, row.key)
            ws.cell(r, C_RKEY, row.remarks_key)
            ws.cell(r, C_ORIG_STATUS, row.status_text)
            ws.cell(r, C_ORIG_REM, remarks)
    last_row = r
    ws.auto_filter.ref = f"A{header}:I{last_row}"
    ws.freeze_panes = ws.cell(header + 1, 1)
    for col in range(C_KEY, C_ORIG_REM + 1):
        ws.column_dimensions[get_column_letter(col)].hidden = True

    r += 2
    ws.cell(r, 1, t["legend"]).font = Font(bold=True)
    for i, key in enumerate(LEGEND):
        fill, font = COLORS[key]
        c = ws.cell(r + 1 + i // 4, 1 + (i % 4) * 2, t["status"][key])
        c.fill, c.font, c.border = PatternFill("solid", fgColor=fill), Font(color=font, bold=True), BOX
        c.alignment = Alignment(horizontal="center")
    ws.cell(r + 3, 1, t["chg_note"]).font = Font(italic=True, color="595959")
    r += 5
    names = (p.mdl_prepared_by, p.mdl_checked_by, p.mdl_approved_by)
    for i, (role, name) in enumerate(zip(t["sign"], names, strict=True)):
        col = 1 + i * 3
        c = ws.cell(r, col, role)
        c.font, c.fill = Font(bold=True, color="FFFFFF"), PatternFill("solid", fgColor=NAVY)
        for j, label in enumerate(t["sign_fields"], start=1):
            ws.cell(r + j, col, label).font = Font(color="595959")
            ws.cell(r + j, col + 1).border = Border(bottom=THIN)
        ws.cell(r + 1, col + 1, name)
    ws.print_title_rows = f"{header}:{header}"
    _print_setup(ws, report)

    hs = wb.create_sheet(t["history"])
    _header_cells(hs, 1, t["history_cols"], (12, 12, 70))
    for i, (rev, d, desc) in enumerate(report.history, start=2):
        for col, v in enumerate((rev, d, desc), start=1):
            c = hs.cell(i, col, v)
            c.border = BOX
            if isinstance(v, date):
                c.number_format = "yyyy-mm-dd"
    _print_setup(hs, report)

    os_ = wb.create_sheet(t["out_sheet"])
    _header_cells(os_, 1, t["out_cols"], (8, 36, 16, 14, 30, 16))
    status_key = {v: k for k, v in t["status"].items()}
    for i, item in enumerate(report.outstanding, start=2):
        for col, v in enumerate(item, start=1):
            os_.cell(i, col, v).border = BOX
        os_.cell(i, 6).fill = PatternFill("solid", fgColor=COLORS[status_key[item[5]]][0])
    if not report.outstanding:
        os_.cell(2, 1, t["none"])
    os_.auto_filter.ref = f"A1:F{max(len(report.outstanding), 1) + 1}"
    os_.freeze_panes = "A2"
    _print_setup(os_, report)

    meta_ws = wb.create_sheet("_meta")
